"""
The report's Summary section, built from the study's own results.

NIEHS Report 10's Summary has a fixed shape, and every number in it is
already in the session:

  1. what the study did (and, when there is a Background, the chemical's
     context — the Background's abstract sentence);
  2. apical BMDs flagged as unreliable (UREP: far below the NOEL/LOEL);
  3. per sex, the most sensitive apical endpoint with a reliable BMD, and the
     next one;
  4. per organ, the most sensitive gene set and gene, by sex;
  5. per sex, the most sensitive point of departure overall, compared with
     the other biological levels.

So it is assembled here deterministically from the same inputs as the
Abstract (the BMD summary entries and the genomics cache), with the Abstract's
reliability rules: no BMD below the lower limit of extrapolation, no anomalous
apical BMD.  Nothing is generated by a model, so the numbers cannot drift
from the tables.
"""

from __future__ import annotations

from narrative.abstract_apical import _format_endpoint_phrase
from narrative.narrative_helpers import (
    genomics_bmd_decimals,
    _format_bmd_value,
    _is_anomalous_bmd,
    _is_reliable_bmd,
    _join_oxford,
    _picks_above_lle,
)

# Two potency estimates within this factor of each other are "in the same range"
# (NIEHS-10: gene 0.510 vs gene set 0.520 mg/kg).
_SAME_RANGE_FACTOR = 2.0


def _pair(item: dict, dose_unit: str, decimals: int | None = None) -> str:
    return (f"{_format_bmd_value(item.get('bmd'), decimals)} "
            f"({_format_bmd_value(item.get('bmdl'), decimals)}) {dose_unit}")


def _phrase(entry: dict) -> str:
    """"increased relative liver weight" — the Abstract's endpoint phrase."""
    return _format_endpoint_phrase(entry.get("endpoint", ""), entry.get("direction", ""),
                                   entry.get("platform", ""))


def _gene_set_name(gs: dict) -> str:
    term = (gs.get("go_term") or "").strip()
    go_id = (gs.get("go_id") or "").strip()
    return f"{term} ({go_id})" if term and go_id else term or go_id or "an unnamed gene set"


def _reliable_apical(entries: list[dict], sex: str) -> list[dict]:
    """Reliable, non-anomalous apical entries of one sex, lowest BMD first."""
    out = [e for e in entries or []
           if e.get("sex") == sex and _is_reliable_bmd(e)
           and not _is_anomalous_bmd(e) and e.get("direction")]
    out.sort(key=lambda e: float(e["bmd"]))
    return out


def _lowest(items: list[dict], lle: float) -> dict | None:
    picks = _picks_above_lle(items or [], lle, n=1)
    return picks[0] if picks else None


def _compare(other: float, pod: float) -> str:
    if other <= pod * _SAME_RANGE_FACTOR and pod <= other * _SAME_RANGE_FACTOR:
        return "in the same range as"
    return "higher than" if other > pod else "lower than"


def build_report_summary(
    apical_bmd_summary: list[dict] | None,
    genomics_sections: dict | None,
    *,
    chemical_name: str,
    dose_groups: list[float] | None = None,
    dose_unit: str = "mg/kg",
    bmd_stat: str | None = None,
    sexes: list[str] | None = None,
    abstract_background: str = "",
    apical_evaluated: bool | None = None,
    bmd_decimals: int | None = None,
    design: dict | None = None,
) -> list[str]:
    """The Summary paragraphs (empty when there is nothing to summarize).

    ``apical_evaluated`` says whether the study measured apical endpoints at
    all (default: whether the BMD summary has entries) — a study can measure
    them and still have none with a BMD.  ``bmd_decimals`` is the report's BMD
    precision (default: the one the genomics extraction stamped).  ``design``
    is the study design (pipeline.study_design) for the species word; None ⇒
    the standard design."""
    from pipeline.study_design import design_or_standard, species_plural

    animals = species_plural(design_or_standard(design))
    apical = apical_bmd_summary or []
    if apical_evaluated is None:
        apical_evaluated = bool(apical)
    genomics = genomics_sections or {}
    if bmd_decimals is None:
        bmd_decimals = genomics_bmd_decimals(genomics)
    sexes = sexes if sexes is not None else ["Male", "Female"]
    nonzero = [d for d in (dose_groups or []) if d and d > 0]
    lle = min(nonzero) / 3.0 if nonzero else 0.0
    if not bmd_stat:
        for sec in genomics.values():
            stats = list((sec or {}).get("gene_sets_by_stat", {}) or {})
            if stats:
                bmd_stat = stats[0]
                break

    def gene_sets(key: str) -> list[dict]:
        return ((genomics.get(key) or {}).get("gene_sets_by_stat") or {}).get(bmd_stat, []) or []

    def genes(key: str) -> list[dict]:
        return (genomics.get(key) or {}).get("top_genes") or []

    paragraphs: list[str] = []
    if not apical_evaluated and not genomics:
        return paragraphs

    # 1. What the study did.
    approach = ("a transcriptomic approach and standard toxicological endpoints"
                if apical_evaluated and genomics else
                "a transcriptomic approach" if genomics else "standard toxicological endpoints")
    intro = f"This study used {approach} to estimate the in vivo biological potency of {chemical_name}."
    paragraphs.append(f"{abstract_background.strip()} {intro}".strip())

    # 2. Unreliable apical BMDs.
    anomalous: dict[str, list[str]] = {}
    for e in apical:
        if e.get("anomalous"):
            anomalous.setdefault(e.get("sex", ""), []).append(
                str(e.get("endpoint", "")).lower())
    if anomalous:
        listed = "; ".join(f"{_join_oxford(names)} in {sex.lower()} {animals}"
                           for sex, names in anomalous.items())
        paragraphs.append(
            f"A subset of standard toxicological endpoints ({listed}) exhibited "
            "benchmark dose (BMD) values much lower than would be expected given "
            "the endpoint-specific no-observed-effect level and lowest-observed-"
            "effect level values. These BMD estimates were flagged as unreliable "
            "estimates of potency and are not considered below.")

    # 3. Most sensitive apical endpoints, per sex.
    if apical_evaluated:
        sentences: list[str] = []
        for sex in sexes:
            rel = _reliable_apical(apical, sex)
            if not rel:
                sentences.append(f"In {sex.lower()} {animals}, there were no apical endpoints "
                                 "for which a BMD value could be reliably estimated.")
                continue
            first = rel[0]
            lead = "Taking this into account, the" if anomalous and not sentences else "The"
            sentences.append(
                f"{lead} most sensitive apical endpoint in {sex.lower()} {animals} was "
                f"{_phrase(first)}, "
                f"with an estimated BMD and benchmark dose lower confidence limit (BMDL) "
                f"of {_pair(first, dose_unit, bmd_decimals)}.")
            if len(rel) > 1:
                nxt = rel[1]
                phrase = _phrase(nxt)
                sentences.append(
                    f"{phrase[:1].upper()}{phrase[1:]} was the next most sensitive "
                    f"apical endpoint in {sex.lower()} {animals}, with a BMD (BMDL) of "
                    f"{_pair(nxt, dose_unit, bmd_decimals)}.")
        paragraphs.append(" ".join(sentences))

    # 4. Per organ: most sensitive gene set and gene, by sex.
    # Liver, then kidney, then the rest alphabetically — the genomics tables' order.
    organ_rank = {"liver": 0, "kidney": 1}
    organs = sorted({key.rsplit("_", 1)[0] for key in genomics},
                    key=lambda o: (organ_rank.get(o, 99), o))
    for organ in organs:
        gs_parts, gene_parts = [], []
        for sex in sexes:
            key = f"{organ}_{sex.lower()}"
            gs = _lowest(gene_sets(key), lle)
            if gs:
                gs_parts.append(f"{_pair(gs, dose_unit, bmd_decimals)} in {sex.lower()} {animals}, "
                                f"corresponding to {_gene_set_name(gs)}")
            g = _lowest(genes(key), lle)
            if g:
                gene_parts.append(f"{g.get('gene_symbol', '')} with a BMD (BMDL) of "
                                  f"{_pair(g, dose_unit, bmd_decimals)} in {sex.lower()} {animals}")
        sentences = []
        if gs_parts:
            sentences.append(
                f"Gene set-level transcriptional changes in the {organ} were estimated "
                f"to occur at a BMD (BMDL) as low as {' and as low as '.join(gs_parts)}.")
        if gene_parts:
            sentences.append(
                f"The most sensitive {organ} gene for which a reliable BMD could be "
                f"determined was {', and '.join(gene_parts)}.")
        if sentences:
            paragraphs.append(" ".join(sentences))

    # 5. Point of departure per sex, compared across levels.
    pod_sentences: list[str] = []
    for sex in sexes:
        cands: list[tuple[float, str, str]] = []  # (bmd, level, description)
        best_gs = best_gene = None
        for organ in organs:
            key = f"{organ}_{sex.lower()}"
            gs = _lowest(gene_sets(key), lle)
            if gs and (best_gs is None or gs["_bmd_float"] < best_gs[0]):
                best_gs = (gs["_bmd_float"], f"a transcriptional change in the gene set "
                           f"{_gene_set_name(gs)} in the {organ} with a BMD (BMDL) of {_pair(gs, dose_unit, bmd_decimals)}")
            g = _lowest(genes(key), lle)
            if g and (best_gene is None or g["_bmd_float"] < best_gene[0]):
                best_gene = (g["_bmd_float"], f"a transcriptional change in the gene "
                             f"{g.get('gene_symbol', '')} in the {organ} with a BMD (BMDL) of {_pair(g, dose_unit, bmd_decimals)}")
        if best_gene:
            cands.append((best_gene[0], "gene", best_gene[1]))
        if best_gs:
            cands.append((best_gs[0], "gene set", best_gs[1]))
        rel = _reliable_apical(apical, sex)
        if rel:
            e = rel[0]
            cands.append((float(e["bmd"]), "apical",
                          f"{_phrase(e)} "
                          f"with a BMD (BMDL) of {_pair(e, dose_unit, bmd_decimals)}"))
        if not cands:
            continue
        cands.sort(key=lambda c: c[0])
        pod_bmd, pod_level, pod_desc = cands[0]
        s = (f"In {sex.lower()} {animals}, the most sensitive point of departure with a "
             f"reliable estimate was {pod_desc}.")
        for bmd, level, _ in cands[1:]:
            what = {"gene": "Individual gene changes", "gene set": "Gene set changes",
                    "apical": "Apical endpoints"}[level]
            s += f" {what} provided potency estimates {_compare(bmd, pod_bmd)} that value."
        if apical_evaluated and not rel and pod_level != "apical":
            s += " There were no apical endpoints with a reliable BMD to compare."
        pod_sentences.append(s)
    if pod_sentences:
        paragraphs.append(
            "Under the conditions of this short-duration study, " +
            pod_sentences[0][0].lower() + pod_sentences[0][1:] +
            ("" if len(pod_sentences) == 1 else " " + " ".join(pod_sentences[1:])))

    return paragraphs
