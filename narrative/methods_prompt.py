"""
LLM prompt assembly for the Materials & Methods section.

The methods narrative is generated by feeding the LLM a system prompt
(role + behavior) and a user prompt (structured study context + the
list of subsections to write).  This module composes both.

Public functions:

  - build_subsection_skeleton(ctx)
      Filter SUBSECTION_SKELETON by the MethodsContext flags to produce
      the ordered list of (key, heading_text, heading_level) tuples
      that should appear in the report.  Conditional subsections
      (Transcriptomics, Clinical Pathology, etc.) drop out when the
      relevant data domain isn't present in the pool.

  - build_methods_prompt(ctx)
      Build the (system_prompt, user_prompt) pair.  The system prompt
      pins style + length + tone; the user prompt embeds the study
      context as labelled key-value lines plus the subsection list and
      per-subsection guidelines from _build_subsection_guidelines.

  - _build_subsection_guidelines(ctx, sub_keys)
      Per-subsection "what the LLM should say here" hints, used by
      build_methods_prompt.  Generated from MethodsContext so the
      guideline values stay in sync with the actual data the prompt
      will receive.

Pulled out of methods_report.py so the prompt-construction surface
lives apart from the data extractor and the narrative builders.
methods_report.py re-exports each name so external call sites
(llm_routes uses build_subsection_skeleton + build_methods_prompt
together) keep working.
"""

# ---------------------------------------------------------------------------
# Imports
# ---------------------------------------------------------------------------

from __future__ import annotations

from bmdx_pipe import bmd_acceptance as _acc

from narrative.methods_models import MethodsContext, SUBSECTION_SKELETON


# ---------------------------------------------------------------------------
# Subsection skeleton: which subsections to include given the context
# ---------------------------------------------------------------------------

def build_subsection_skeleton(ctx: MethodsContext) -> list[tuple[str, str, int]]:
    """
    Determine which M&M subsections to include based on domain presence.

    Returns a list of (subsection_key, heading_text, heading_level) tuples
    in the correct order for both the LLM prompt and the rendered report.

    Args:
        ctx: MethodsContext with domain presence flags set.

    Returns:
        Filtered list of subsections that apply to this study.
    """
    skeleton = []
    for key, heading, level, condition in SUBSECTION_SKELETON:
        if condition is None:
            # Always included
            skeleton.append((key, heading, level))
        else:
            # Check the condition field on MethodsContext
            if getattr(ctx, condition, False):
                skeleton.append((key, heading, level))
    return skeleton


# ---------------------------------------------------------------------------
# LLM prompt builder
# ---------------------------------------------------------------------------

def build_methods_prompt(ctx: MethodsContext) -> tuple[str, str]:
    """
    Build the structured LLM prompt for M&M generation.

    Returns (system_prompt, user_prompt) strings.

    The user prompt includes all extracted study context and asks the LLM
    to return a JSON object keyed by subsection key.  Only keys for
    present domains are requested.

    Args:
        ctx: Populated MethodsContext.

    Returns:
        Tuple of (system_prompt, user_prompt).
    """
    system = (
        "You are a toxicology report writer specializing in NTP/NIEHS-style "
        "technical reports for 5-day genomic dose-response studies. "
        "Write precise, formal scientific text. "
        "Return ONLY valid JSON with no markdown formatting."
    )

    # Build the study context block with actual data
    dose_str = ", ".join(str(d) for d in ctx.dose_groups) if ctx.dose_groups else "not specified"
    # A study with no sex dimension (e.g. a pooled / single-cohort S1500+ transcriptomics
    # run) has ctx.sexes empty. Do NOT fall back to "male and female" — assert nothing about
    # sex, so the LLM writes sex-neutral prose instead of inventing per-sex cohorts.
    sexless = not ctx.sexes
    sexes_str = " and ".join(ctx.sexes)

    sex_line = "- Sexes: not applicable (no sex dimension in this study)" if sexless else f"- Sexes: {sexes_str}"
    _unk = "not available in the data — do not state a number"
    per_group = (_unk if ctx.n_per_group is None else
                 f"{ctx.n_per_group} per dose" if sexless else f"{ctx.n_per_group} {sexes_str} per dose")
    control_n = (_unk if ctx.n_control is None else
                 f"{ctx.n_control}" if sexless else f"{ctx.n_control} {sexes_str}")

    context_block = f"""## Study Context
- Chemical: {ctx.chemical_name} (CASRN: {ctx.casrn}, DTXSID: {ctx.dtxsid})
- Species: {ctx.species} rats
{sex_line}
- Route of administration: oral {ctx.route}
- Vehicle: {ctx.vehicle}
- Duration: {ctx.duration_days} days
- Dose groups ({ctx.dose_unit}): {dose_str}
- Animals per treatment group: {per_group}
- Animals in vehicle control: {control_n}"""

    if ctx.n_biosampling > 0:
        context_block += f"\n- Biosampling animals: {ctx.n_biosampling} total"

    # Domain-specific context
    if ctx.has_organ_weights and ctx.organ_weight_endpoints:
        context_block += f"\n- Organs weighed: {', '.join(ctx.organ_weight_endpoints)}"
    if ctx.has_clin_chem and ctx.clin_chem_endpoints:
        context_block += f"\n- Clinical chemistry parameters: {', '.join(ctx.clin_chem_endpoints)}"
    if ctx.has_hematology and ctx.hematology_endpoints:
        context_block += f"\n- Hematology parameters: {', '.join(ctx.hematology_endpoints)}"
    if ctx.has_hormones and ctx.hormone_endpoints:
        context_block += f"\n- Hormone parameters: {', '.join(ctx.hormone_endpoints)}"
    if ctx.has_gene_expression and ctx.ge_organs:
        context_block += f"\n- Transcriptomics organs: {', '.join(ctx.ge_organs)}"
    if ctx.has_tissue_conc:
        context_block += "\n- Internal dose assessment: tissue concentration data available"

    # BMDExpress metadata
    if ctx.bmdexpress_version:
        context_block += f"\n- BMDExpress version: {ctx.bmdexpress_version}"
    if ctx.bmds_version:
        context_block += f"\n- BMDS version: {ctx.bmds_version}"
    if ctx.models_fit:
        context_block += f"\n- BMD models fit: {', '.join(ctx.models_fit)}"
    if ctx.bmr_type:
        context_block += f"\n- BMR type: {ctx.bmr_type}"
    if ctx.bmr_factor is not None:
        context_block += f"\n- BMR factor: {ctx.bmr_factor}"
    if ctx.prefilter_method:
        context_block += f"\n- Pre-filter method: {ctx.prefilter_method}"
    if ctx.prefilter_pvalue is not None:
        context_block += f"\n- Pre-filter p-value cutoff: {ctx.prefilter_pvalue}"
    if ctx.constant_variance is not None:
        context_block += f"\n- Constant variance: {'yes' if ctx.constant_variance else 'no'}"

    # Build subsection requirements
    skeleton = build_subsection_skeleton(ctx)
    subsection_keys = [key for key, _, _ in skeleton]

    # Per-subsection guidance for the LLM
    guidelines = _build_subsection_guidelines(ctx, skeleton)

    # For a sex-less study, tell the LLM not to invent sex wording anywhere (it otherwise
    # elaborates "male and female" into per-sex normalization / cohorts on its own).
    sexless_note = (
        "\n- This study has NO sex dimension: do NOT mention sex anywhere — no "
        "\"male and female\", no per-sex cohorts, no sex-specific normalization or "
        "analysis. Refer to the animals sex-neutrally (\"rats\", \"animals\")."
        if sexless else ""
    )

    user_prompt = f"""Generate the Materials and Methods section for a {ctx.duration_days}-day genomic dose-response study report.

{context_block}

## Required Subsections
Generate content for ONLY the following subsections (in order).
Return your response as a JSON object where each key is a subsection identifier
and the value is a string containing 1-3 paragraphs of prose.

Keys to generate: {subsection_keys}

{guidelines}

## Important formatting notes:
- Do NOT include section headers in the text — they will be added by the template.
- Write in past tense, third person, formal NIEHS/NTP technical report style.
- Reference exact study parameters from the context above (dose groups, species, etc.).
- Each value should be a single string. Use \\n\\n to separate multiple paragraphs within a subsection.
- Return ONLY the JSON object, no markdown code fences.{sexless_note}"""

    return system, user_prompt


def _dose_spacing_phrase(ctx: MethodsContext) -> str:
    """The spacing the dose groups actually have, e.g. "approximately 2-fold
    spacing between consecutive doses" (a fixed "half-log" was wrong for most
    studies)."""
    import statistics

    doses = sorted(d for d in (ctx.dose_groups or []) if d and d > 0)
    ratios = [b / a for a, b in zip(doses, doses[1:]) if a > 0]
    if not ratios:
        return "dose spacing as designed"
    r = statistics.median(ratios)
    if abs(r - 10 ** 0.5) < 0.25:
        return "approximately half-log spacing between consecutive doses"
    return f"approximately {r:.1f}-fold spacing between consecutive doses"


def _genomic_bmr_phrase(ctx: MethodsContext) -> str:
    """The genomic BMR as recorded in the .bm2 ("25% relative deviation")."""
    t, f = (ctx.bmr_type or "").lower(), ctx.bmr_factor
    if "relative" in t and f is not None:
        return f"{f * 100:g}% relative deviation"
    if f is not None:
        return f"{f:g} standard deviation"
    return ctx.bmr_type or ""


def _apical_bmr_phrase(ctx: MethodsContext) -> str:
    """The apical BMR for the assay families present, from the same per-family
    defaults tables.apical_bmds applies when a platform records no config."""
    from tables.apical_bmds import _ASSAY_FAMILY_BMR, _BMR_REL

    present = [name for name, has in (
        ("body weight", ctx.has_body_weight), ("organ weight", ctx.has_organ_weights),
        ("clinical chemistry", ctx.has_clin_chem), ("hematology", ctx.has_hematology),
        ("hormones", ctx.has_hormones),
    ) if has]
    by_bmr: dict[str, list[str]] = {}
    for fam in present:
        kind, factor = _ASSAY_FAMILY_BMR[fam]
        label = (f"{factor * 100:g}% relative deviation" if kind == _BMR_REL
                 else f"{factor:g} standard deviation")
        by_bmr.setdefault(label, []).append(fam)
    if len(by_bmr) <= 1:
        return next(iter(by_bmr), "1 standard deviation")
    return "; ".join(f"{label} ({', '.join(fams)})" for label, fams in by_bmr.items())


def _build_subsection_guidelines(
    ctx: MethodsContext,
    skeleton: list[tuple[str, str, int]],
) -> str:
    """
    Build per-subsection prose guidelines for the LLM prompt.

    Each guideline tells the LLM exactly what to cover in that subsection
    and references the actual study parameters from the context.

    Args:
        ctx:      MethodsContext with study parameters.
        skeleton: The filtered subsection skeleton.

    Returns:
        Formatted string of guidelines.
    """
    dose_str = ", ".join(str(d) for d in ctx.dose_groups) if ctx.dose_groups else "not specified"
    sexless = not ctx.sexes
    sexes_str = " and ".join(ctx.sexes)
    if ctx.n_per_group is None or ctx.n_control is None:
        sample_sizes = "group sizes are not available in the data; do not state animal counts"
    else:
        sample_sizes = (
            f"{ctx.n_per_group} per treatment group, {ctx.n_control} vehicle control"
            if sexless else
            f"{ctx.n_per_group} {sexes_str} per treatment group, {ctx.n_control} {sexes_str} vehicle control"
        )

    guides: dict[str, str] = {
        "study_design": (
            f"One paragraph covering: animal source and quarantine (7 days), "
            f"randomization by body weight, dose groups ({dose_str} {ctx.dose_unit}), "
            f"dosing schedule ({ctx.duration_days} consecutive days by oral {ctx.route}), "
            f"sample sizes ({sample_sizes}), "
            f"{'biosampling animals for internal dose assessment, ' if ctx.n_biosampling > 0 else ''}"
            f"necropsy timing (approximately 24 hours after the final dose)."
        ),
        "dose_selection": (
            "One paragraph. Reference LD50 predictions if available, "
            f"explain the dose spacing rationale ({_dose_spacing_phrase(ctx)}), "
            "rationale for top dose selection, and target of no overt systemic toxicity."
        ),
        "chemistry": (
            f"First paragraph: {ctx.chemical_name} source (typically synthesized by contract lab or obtained from commercial supplier), "
            f"lot number (state that lot details are in the full study protocol), "
            f"identity confirmation methods (IR, NMR, or mass spectrometry), purity (typically >95%%), storage conditions. "
            f"Second paragraph: dose formulation preparation in {ctx.vehicle}, "
            f"concentration verification by analytical chemistry, formulation QC analysis."
        ),
        "clinical_exams": (
            "Brief introductory paragraph describing the scope of clinical examinations "
            "performed during the study: clinical observations, body/organ weight collection, "
            "clinical pathology sampling, and (if applicable) tissue collection for internal dose assessment."
        ),
        "clinical_obs": (
            "One paragraph. Standard boilerplate: animals were observed twice daily for morbidity/mortality, "
            "clinical observations were recorded once daily, "
            "cage-side observations included assessment of general appearance, behavior, and respiratory patterns."
        ),
        "body_organ_weights": (
            f"One paragraph. Body weights recorded on study day 0 and at necropsy on study day "
            f"{ctx.duration_days} (do not state any other necropsy day). "
            f"{'Organ weights: ' + ', '.join(ctx.organ_weight_endpoints[:10]) + '.' if ctx.organ_weight_endpoints else 'Organs were weighed at necropsy.'} "
            f"Absolute and relative (organ-to-body-weight ratio) weights calculated."
        ),
        "clinical_pathology": (
            f"One paragraph covering blood collection method (retroorbital or cardiac puncture under anesthesia), "
            f"sample processing. "
            f"{'Clinical chemistry parameters: ' + ', '.join(ctx.clin_chem_endpoints[:10]) + '. ' if ctx.clin_chem_endpoints else ''}"
            f"{'Hematology parameters: ' + ', '.join(ctx.hematology_endpoints[:10]) + '. ' if ctx.hematology_endpoints else ''}"
            f"{'Hormone parameters: ' + ', '.join(ctx.hormone_endpoints[:5]) + '. ' if ctx.hormone_endpoints else ''}"
            f"Reference the analyzer instruments (e.g., Advia 120 for hematology, AU680 for clinical chemistry)."
        ),
        "internal_dose": (
            "One paragraph. Describe tissue collection for internal dose assessment: "
            "blood/serum and tissue samples collected at necropsy, stored at -80°C, "
            "analyzed by LC-MS/MS for parent compound and/or metabolite concentrations."
        ),
        "transcriptomics": (
            f"Brief introductory paragraph: transcriptomic profiling was performed on "
            f"{', '.join(ctx.ge_organs) if ctx.ge_organs else 'target organs'} "
            f"using the TempO-Seq targeted RNA sequencing platform (BioSpyder Technologies)."
        ),
        "txomics_sample": (
            "One paragraph. RNA was isolated from flash-frozen tissue samples. "
            "Describe tissue homogenization, RNA extraction method (e.g., RNeasy), "
            "RNA quality assessment (RIN values)."
        ),
        "txomics_rna": (
            "One paragraph. TempO-Seq S1500+ platform (BioSpyder Technologies), "
            "library preparation with detector oligos, ligation, amplification, "
            "multiplexed sequencing on Illumina platform."
        ),
        "txomics_seq_processing": (
            "One paragraph. Demultiplexing, alignment to probe reference sequences, "
            "count table generation using the TempO-SeqR pipeline."
        ),
        "txomics_qc": (
            "One paragraph. Outlier detection by principal component analysis and "
            "total read count thresholds. Samples below quality thresholds were excluded "
            "from downstream analysis."
        ),
        "txomics_normalization": (
            "One paragraph. The current NIEHS TempO-Seq normalization: aligned read counts "
            "of attenuated probes were readjusted to unattenuated equivalents using the "
            "platform manifest's attenuation factors; counts were normalized per probe to "
            "reads per million; a pseudo-count of 1.0 was added and values were "
            "log2-transformed. Do NOT mention DESeq2, TMM or differential-expression models."
        ),
        "data_analysis": (
            "Brief introductory paragraph: overview of the statistical and dose-response "
            "modeling approaches applied to both apical and transcriptomic endpoints."
        ),
        "stat_analysis": (
            "One or two paragraphs, the NIEHS method: organ and body weight data "
            "(approximately normal) were analyzed with the parametric multiple-comparison "
            "procedures of Williams and Dunnett; clinical pathology data (typically skewed) "
            "with the nonparametric procedures of Shirley and Dunn. The Jonckheere test "
            "assessed dose-response trends and selected the trend-sensitive test (Williams or "
            "Shirley) when significant at p <= 0.01, otherwise Dunnett or Dunn. Values flagged "
            "by the Dixon and Massey outlier test were examined, and values from animals "
            "suspected of illness unrelated to exposure or flagged for measurement problems were "
            "eliminated. NOEL = highest dose without a significant (p <= 0.05) pairwise "
            "difference from the vehicle control; LOEL = lowest dose with one. Do not mention "
            "normality or variance-homogeneity tests (Shapiro-Wilk, Levene). Only mention "
            "clinical pathology if it is in the context."
        ),
        "bmd_apical": (
            "One paragraph. Apical BMD modeling used nontransformed individual-animal data. "
            "Except for body weights, an endpoint was modeled only if it showed a significant "
            "trend and at least one significant pairwise difference. Modeling used ToxicR "
            "Laplace model averaging of the Hill, Power, Exponential 3 and Exponential 5 "
            f"models with constant variance and a benchmark response of {_apical_bmr_phrase(ctx)}. "
            f"Modeled responses were excluded unless R2 >= {_acc.R2_MIN:g}, BMD/BMDL <= "
            f"{_acc.BMD_BMDL_MAX:g} and BMD <= the highest dose; an endpoint meeting the "
            "statistical criteria without a viable model is reported as having no viable "
            "model. The genomic BMR in the context does NOT apply to apical endpoints."
        ),
        "bmd_genomics": (
            f"One or two paragraphs. Transcriptomic BMD analysis in "
            f"{ctx.bmdexpress_version or 'BMDExpress 3'}: probes with a zero count in any "
            f"sample were excluded; a Williams trend prefilter"
            f"{' (p < ' + str(ctx.prefilter_pvalue) + ')' if ctx.prefilter_pvalue else ''} "
            f"followed by the Curve Fit Prefilter; BMD modeling with ToxicR Laplace model "
            f"averaging{' of ' + ', '.join(ctx.models_fit) if ctx.models_fit else ''}"
            f"{', BMR ' + _genomic_bmr_phrase(ctx) if ctx.bmr_type else ''}, constant variance. "
            f"GO biological process gene-set analysis with these recorded settings: "
            f"{'; '.join(ctx.go_filter_settings) if ctx.go_filter_settings else 'not recorded'}. "
            f"Gene sets were reported when at least 3 genes passed all filters and at least 5% "
            f"of the set was populated; BMD, BMDL and BMDU at the 5th percentile of the set's "
            f"gene BMDs were the potency metrics. Individual-gene results were the median over "
            f"the probes mapped to each gene. Use ONLY these settings; do not invent others."
        ),
        "efdr": (
            "One or two sentences: empirical false discovery rate results (synthetic null "
            "data processed with the same parameters) are not included in this report's data "
            "package. Do not describe a permutation procedure or give rates."
        ),
        "data_accessibility": (
            "One paragraph. Data availability statement: "
            "all raw and processed data are available through the NIEHS Chemical Effects "
            "in Biological Systems (CEBS) database or the study's data repository. "
            "Provide placeholder for DOI or accession number."
        ),
    }

    lines = ["## Guidelines per subsection:"]
    for key, heading, level in skeleton:
        if key in guides:
            lines.append(f"- {key}: {guides[key]}")

    return "\n".join(lines)


