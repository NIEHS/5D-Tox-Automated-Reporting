"""rendering.bookshelf_preview — render a BITS <book> into a visually faithful
NCBI-Bookshelf-style HTML preview, page by page.

This transforms the EXACT artifact we submit (the BITS book emitted by
`jats_generator.generate_bits`) into an HTML page styled and *navigated* like the
reader view of a book on NCBI Bookshelf: a **Contents landing** (title block,
the book-meta abstract, the parts with their sections nested, as the published
<toc>) plus **one page per part** — rendered as the book has it, labels and
headings included (ADR-0028), nothing unwrapped or invented — with
``< Prev`` / ``Next >`` pagination, a "Contents"
link, and a right-hand rail of "Views" (downloads) + a section navigator.  The
whole book is emitted into ONE self-contained HTML document; navigation between
"pages" is client-side (hash-routed, ``#<section-id>``), so the module's public
API still returns a single string that the CLI, the preview surface and saved
``output/*.html`` all consume unchanged.  Cross-references (``xref``) across
pages work: a click switches to the target's page and scrolls to it.

The content column mirrors the real Bookshelf reader DOM (``main-content
lit-style`` › ``meta-content fm-sec`` h1 with ``label``/``title`` spans ›
``body-content whole_rhythm``, ``temp-labeled-list`` footnotes,
``pagination``/``page_link``).  As in the real reader, data tables and figures
render as floated **thumbnail cards** (``iconblock table-wrap``): a shrunk
preview + "Table/Figure N" heading + caption, whose full object opens in a
client-side **lightbox** on click and shows a peek preview on hover; inline
prose references to a table/figure open the same lightbox.  Matching those class
names means a copy of NCBI's real ``books.min.css`` dropped at
``assets/bookshelf/bookshelf.css`` styles the content faithfully with no code
change (see ``_stylesheet``).

It is a LOOKALIKE, deliberately scoped to the reader CONTENT.  It does NOT
reproduce NCBI's site chrome — the U.S.-government banner, the NIH/NLM/NCBI
logos and universal header, the portlets or the NCBI footer.  That markup is
generated by NCBI's portal framework from their own (unpublished) production
XSLT, and reproducing it would be impersonation.  A prominent banner marks every
page as a preview, not an NCBI/NIEHS page.  It is a preview of the ultimate
deliverable, never a substitute for NCBI's own QA render.

The Contents landing — title block, abstract, contents, About the Series — and
the rail's Cite this Page are rendering.bookshelf_landing, matched to the real
landing page of NIEHS Report 10.

It renders a chunked Bookshelf bundle (TOC.nxml + one file per part) the same
way — our `bits` surface, or a PUBLISHED book from assets/cebs/_bookshelf — so
ours and the published report of a study can be read side by side.

Public API:
    render_book_xml(xml, base_dir=None, images=None, downloads=None) -> str
    render_book_file(path) -> str          a BITS file or a bundle directory
    chart_images(data) -> {filename: base64 image}
"""

from __future__ import annotations

import html
import itertools
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from lxml import etree

XLINK = "http://www.w3.org/1999/xlink"

# Optional vendored real Bookshelf stylesheet; overrides the built-in CSS.
_REPO = Path(__file__).resolve().parents[1]
_VENDORED_CSS = _REPO / "assets" / "bookshelf" / "bookshelf.css"

# Block-level BITS elements we render inside a body/section (anything else at the
# block level — book-part-meta, title — is handled by the caller or ignored).
_BLOCK_TAGS = frozenset({"sec", "p", "table-wrap", "fig", "list", "boxed-text", "media",
                         "supplementary-material", "disp-formula", "ref-list"})
MATHML = "http://www.w3.org/1998/Math/MathML"

# Per-render counter giving an id to a table/figure that carries none, so every
# object has a stable lightbox target within one document.  Reset at the top of
# _build_html (rendering is single-pass per document).
_OBJ_COUNTER = {"seq": itertools.count(1)}
_FORMULA_COUNTER = {"n": 0}     # display formulas on the page being rendered


def _next_obj_id() -> str:
    return f"obj{next(_OBJ_COUNTER['seq'])}"


def _ln(el) -> str:
    """Local name of an element tag (namespace-stripped)."""
    return etree.QName(el).localname if isinstance(el.tag, str) else ""


def _esc(s: str | None) -> str:
    return html.escape(s or "", quote=True)


# ---------------------------------------------------------------------------
# Inline runs (text + <ext-link>/<xref>/<italic>/<bold>/<sub>/<sup>)
# ---------------------------------------------------------------------------

def _inline(el) -> str:
    """Serialize an element's mixed inline content to HTML, preserving tails."""
    parts: list[str] = []
    if el.text:
        parts.append(_esc(el.text))
    for child in el:
        parts.append(_inline_child(child))
        if child.tail:
            parts.append(_esc(child.tail))
    return "".join(parts)


def _inline_child(child) -> str:
    tag = _ln(child)
    inner = _inline(child)
    if tag == "ext-link":
        href = child.get(f"{{{XLINK}}}href") or child.get("href") or ""
        return (f'<a href="{_esc(href)}" target="_blank" rel="noopener">'
                f'{inner or _esc(href)}</a>')
    if tag == "xref":
        rid = child.get("rid", "")
        return f'<a class="xref bk_pop" href="#{_esc(rid)}">{inner}</a>'
    if tag == "related-object":
        # A chunked bundle's link into another part file (a reference in the
        # References part, an appendix, a table): the object, else the part.
        target = child.get("object-id") or child.get("document-id") or ""
        if target:
            return f'<a class="bk_pop" href="#{_esc(target)}">{inner}</a>'
    if tag in ("italic", "i"):
        return f"<i>{inner}</i>"
    if tag in ("bold", "b"):
        return f"<b>{inner}</b>"
    if tag == "sub":
        return f"<sub>{inner}</sub>"
    if tag == "sup":
        return f"<sup>{inner}</sup>"
    if tag == "underline":
        return f"<u>{inner}</u>"
    if tag == "break":
        return "<br/>"
    if tag == "monospace":
        return f'<code class="bk_tt">{inner}</code>'
    # Unknown inline element: keep its text content, drop the wrapper.
    return inner


def _inline_no_fn(el) -> str:
    """An element's inline content without its <fn>s (a caption paragraph whose
    footnotes Bookshelf lists under the figure instead)."""
    parts = [_esc(el.text)] if el.text else []
    for child in el:
        if _ln(child) != "fn":
            parts.append(_inline_child(child))
        if child.tail:
            parts.append(_esc(child.tail))
    return "".join(parts)


def _ws_text(el) -> str:
    """An element's text with whitespace (and no-break spaces) collapsed."""
    if el is None:
        return ""
    return " ".join("".join(el.itertext()).replace("\u00a0", " ").split())


def _title_text(el) -> str:
    """Plain-text title of a sec/part (for the TOC), from its <title> child."""
    t = el.find("title")
    return "".join(t.itertext()).strip() if t is not None else ""


# ---------------------------------------------------------------------------
# Tables — real Bookshelf DOM: div.table › h3(label+title) › div.large_tbl ›
# table.no_margin, with temp-labeled-list footnotes.
# ---------------------------------------------------------------------------

def _render_table(table_el) -> str:
    groups: list[str] = []
    for section in table_el:
        stag = _ln(section)
        if stag not in ("thead", "tbody", "tfoot"):
            continue
        rows: list[str] = []
        for tr in section:
            if _ln(tr) != "tr":
                continue
            cells: list[str] = []
            for cell in tr:
                ctag = _ln(cell)
                if ctag not in ("th", "td"):
                    continue
                span = cell.get("colspan")
                attrs = f' colspan="{_esc(span)}"' if span else ""
                # A spanning td is a group/sex sub-header row in our tables.
                cls = ' class="grouprow"' if (ctag == "td" and span) else ""
                cells.append(f"<{ctag}{attrs}{cls}>{_inline(cell)}</{ctag}>")
            rows.append("<tr>" + "".join(cells) + "</tr>")
        groups.append(f"<{stag}>" + "".join(rows) + f"</{stag}>")
    return '<table class="no_margin">' + "".join(groups) + "</table>"


def _temp_labeled(inner_html: str) -> str:
    """A Bookshelf ``temp-labeled-list`` block — the small footnote/abbreviation
    list rendered under tables and figures."""
    return ('<div><dl class="temp-labeled-list small"><dt></dt><dd><div>'
            f'{inner_html}</div></dd></dl></div>')


def _fn_list(fns, p_class: str) -> str:
    """Footnotes as Bookshelf lists them: one ``dt`` (the footnote's label, empty
    when it has none) and ``dd`` per <fn>."""
    items = []
    for fn in fns:
        lab = fn.find("label")
        dt = _inline(lab) if lab is not None else ""
        paras = "".join(f'<p class="{p_class}">{_inline(p)}</p>' for p in fn.findall("p"))
        items.append(f'<dt>{dt}</dt><dd><div{_id_attr(fn.get("id"))}>{paras}</div></dd>')
    return (f'<div><dl class="temp-labeled-list small">{"".join(items)}</dl></div>'
            if items else "")


def _id_attr(i: str | None) -> str:
    return f' id="{_esc(i)}"' if i else ""


def _caption_html(obj) -> str:
    """The caption heading of a table/figure/media object: its <caption><title>
    (how the published books title a table), else its first <caption><p> (a
    figure's), else the caption's text."""
    cap = obj.find("caption")
    if cap is None:
        return ""
    for tag in ("title", "p"):
        el = cap.find(tag)
        if el is not None:
            return _inline(el)
    return _inline(cap)


def _render_table_wrap(el) -> str:
    tid = el.get("id") or _next_obj_id()
    obj_id = f"obj-{tid}"
    label = _ws_text(el.find("label"))
    caption_html = _caption_html(el)
    table = el.find("table")
    table_html = _render_table(table) if table is not None else ""
    foot = ""
    twf = el.find("table-wrap-foot")
    if twf is not None:
        notes = ["".join(f'<p class="no_margin">{_inline(p)}</p>'
                         for p in fn.findall("p"))
                 for fn in twf.findall("fn")]
        notes += [f'<p class="no_margin">{_inline(p)}</p>' for p in twf.findall("p")]
        if notes:
            foot = _temp_labeled("".join(notes))
    lab = _esc(label) if label else "Table"
    if el.get("position") == "anchor":
        # An anchored table stands in the text in full, as Bookshelf shows it
        # (the appendices' tables); a floating one is a card (below).
        if twf is not None:
            foot = _fn_list(twf.findall("fn"), "no_margin") + "".join(
                _temp_labeled(f'<p class="no_margin">{_inline(p)}</p>') for p in twf.findall("p"))
        title = f'<span class="title">{caption_html}</span>' if caption_html else ""
        return (f'<div id="{_esc(tid)}" class="table"><h3><span class="label">{lab}</span>'
                f'{title}</h3><div class="large_tbl">{table_html}</div>{foot}</div>')
    # Full object — opens in the lightbox / hover preview; hidden in-flow.
    obj_head = (f'<h3><span class="label">{lab}</span> '
                f'<span class="title">{caption_html}</span></h3>') if (label or caption_html) else ""
    obj = (f'<div class="bk-object" id="{_esc(obj_id)}">{obj_head}'
           f'<div class="large_tbl">{table_html}</div>{foot}</div>')
    # Thumbnail card in the reading column (real Bookshelf renders data tables as
    # a floated thumbnail that opens the full table on click), its caption closed
    # with a full stop as Bookshelf does ("…Data. ").
    stop = "" if re.search(r"[.?!:]\s*$", _ws_text(el.find("caption/title"))) else "."
    caption_card = (f'<p class="float-caption">{caption_html}{stop} </p>'
                    if caption_html else "")
    card = (f'<div class="iconblock table-wrap clearfix" id="{_esc(tid)}">'
            f'<a class="icnblk_img figpopup bk-figpopup" data-obj="{_esc(obj_id)}" '
            f'title="{lab}" role="button" tabindex="0">'
            f'<span class="bk-thumb"><span class="bk-thumb-scale">{table_html}</span>'
            f'<span class="bk-thumb-zoom" aria-hidden="true">&#128269;</span></span></a>'
            f'<div class="icnblk_cntnt"><h4><a class="bk-figpopup" data-obj="{_esc(obj_id)}" '
            f'role="button" tabindex="0">{lab}</a></h4>{caption_card}</div></div>')
    return card + obj


_IMAGE_TYPES = {".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg",
                ".gif": "image/gif", ".svg": "image/svg+xml"}


def _bundle_image(base_dir: Path, href: str) -> str:
    """A graphic next to the BITS file, inlined as a data URI so the page is
    self-contained wherever it is saved.  Published bundles name a graphic
    without its extension (xlink:href="NIEHS_10-Image001" → …Image001.jpg)."""
    import base64
    for ext in ("", *_IMAGE_TYPES):
        path = base_dir / f"{href}{ext}"
        mime = _IMAGE_TYPES.get(path.suffix.lower())
        if mime and path.is_file():
            return f"data:{mime};base64,{base64.b64encode(path.read_bytes()).decode()}"
    return ""


def _render_fig(el, base_dir: Path | None, images: dict | None) -> str:
    fid = el.get("id") or _next_obj_id()
    obj_id = f"obj-{fid}"
    label = _ws_text(el.find("label"))
    caption_html = _caption_html(el)
    graphic = el.find("graphic")
    href = ""
    if graphic is not None:
        href = graphic.get(f"{{{XLINK}}}href") or graphic.get("href") or ""
    # An `images` map (filename → base64 PNG, supplied by the caller from the
    # session data) makes the preview self-contained: the BITS <graphic> only
    # references a filename, so the bytes are inlined here as a data URI.  Falls
    # back to a real file next to the page, then a visible placeholder.
    alt = _esc(label or caption_html)
    b64 = (images or {}).get(href)
    if b64:
        src = b64 if b64.startswith("data:") else f"data:image/png;base64,{b64}"
        img = f'<img src="{src}" alt="{alt}">'
        have_img = True
    elif href and base_dir is not None and _bundle_image(base_dir, href):
        img = f'<img src="{_bundle_image(base_dir, href)}" alt="{alt}">'
        have_img = True
    else:
        img = f'<div class="fig-missing">[figure: {_esc(href or "image not bundled")}]</div>'
        have_img = False
    lab = _esc(label) if label else "Figure"
    lab_h3 = f'<h3><span class="label">{lab}</span></h3>' if label else ""
    if el.get("position") == "anchor":
        # An anchored figure stands in the text: the image, its label, the
        # caption's paragraphs, the source line (<attrib>) and the caption's
        # footnotes listed under it — Bookshelf's figure block.
        cap = el.find("caption")
        paras = "".join(f"<p>{_inline_no_fn(p)}</p>" for p in cap.findall("p")) if cap is not None else ""
        attrib = "".join(f"<p>{_inline(a)}</p>" for a in el.findall("attrib"))
        notes = _fn_list(cap.iter("fn"), "no_top_margin") if cap is not None else ""
        return (f'<div id="{_esc(fid)}" class="figure bk_fig"><div class="graphic">{img}</div>'
                f'{lab_h3}<div class="caption">{paras}</div>{attrib}{notes}</div>')
    caption_div = f'<div class="caption"><p>{caption_html}</p></div>' if caption_html else ""
    # Full object (lightbox / hover), hidden in-flow.
    obj = (f'<div class="bk-object" id="{_esc(obj_id)}"><div class="figure bk_fig">'
           f'<div class="graphic">{img}</div>{lab_h3}{caption_div}</div></div>')
    # Thumbnail card.
    thumb_cls = "bk-thumb bk-thumb-img" if have_img else "bk-thumb bk-thumb-missing"
    caption_card = f'<p class="float-caption">{caption_html}</p>' if caption_html else ""
    card = (f'<div class="iconblock fig-wrap clearfix" id="{_esc(fid)}">'
            f'<a class="icnblk_img figpopup bk-figpopup" data-obj="{_esc(obj_id)}" '
            f'title="{lab}" role="button" tabindex="0">'
            f'<span class="{thumb_cls}">{img}'
            f'<span class="bk-thumb-zoom" aria-hidden="true">&#128269;</span></span></a>'
            f'<div class="icnblk_cntnt"><h4><a class="bk-figpopup" data-obj="{_esc(obj_id)}" '
            f'role="button" tabindex="0">{lab}</a></h4>{caption_card}</div></div>')
    return card + obj


# ---------------------------------------------------------------------------
# Section / body walk
# ---------------------------------------------------------------------------

def _render_blocks(children, level: int, out: list[str], base_dir: Path | None,
                   images: dict | None) -> None:
    for el in children:
        tag = _ln(el)
        if tag == "sec":
            _render_sec(el, level, out, base_dir, images)
        elif tag == "p":
            out.append(f"<p>{_inline(el)}</p>")
        elif tag == "table-wrap":
            out.append(_render_table_wrap(el))
        elif tag == "fig":
            out.append(_render_fig(el, base_dir, images))
        elif tag == "list":
            out.append(_render_list(el))
        elif tag in ("media", "supplementary-material"):
            out.append(_render_media(el, base_dir))
        elif tag == "disp-formula":
            _FORMULA_COUNTER["n"] += 1
            out.append(_render_formula(el, _FORMULA_COUNTER["n"]))
        elif tag == "ref-list":
            out.append(_render_ref_list(el))
        elif tag == "boxed-text":
            inner: list[str] = []
            _render_blocks(list(el), level, inner, base_dir, images)
            out.append(f'<div class="boxed">{"".join(inner)}</div>')
        # book-part-meta, title, etc. handled by the caller / ignored here.


def _render_list(el) -> str:
    """<list>: one <li> per item.  An item of several paragraphs (the published
    Authors / Contributors lists: affiliation, contributions, one name per
    paragraph) keeps them as separate lines, classed by @content-type."""
    tag = "ol" if el.get("list-type") == "order" else "ul"
    simple = el.get("list-type") == "simple"
    cls = "simple-list" if simple else "bk-list"
    items = []
    for li in el.findall("list-item"):
        paras = li.findall("p")
        if paras:
            inner = "".join(
                f'<div{_class_attr(p.get("content-type"))}>{_inline(p)}</div>' for p in paras)
        else:
            inner = _inline(li)
        items.append(f'<li class="half_rhythm">{inner if paras else f"<div>{inner}</div>"}</li>')
    return f'<{tag} class="{cls}">{"".join(items)}</{tag}>'


def _class_attr(cls: str | None) -> str:
    return f' class="{_esc(cls)}"' if cls else ""


# Bookshelf's names for a supplied file's type; any other is its extension in
# capitals ("BM2", "ZIP").
_FILE_KINDS = {"doc": "MS Word", "docx": "MS Word", "xls": "MS Excel", "xlsx": "MS Excel",
               "txt": "Text", "pdf": "PDF", "ppt": "MS PowerPoint", "pptx": "MS PowerPoint"}


def _file_size(n: int) -> str:
    """A file size as Bookshelf prints it: K under 1024K, else M; one decimal
    (truncated) under 10, else a whole number ("7.9K", "15K", "1.2M", "26M")."""
    import math
    v, unit = n / 1024, "K"
    if v >= 1024:
        v, unit = v / 1024, "M"
    return f"{math.floor(v * 10) / 10:.1f}{unit}" if v < 10 else f"{round(v)}{unit}"


def _render_media(el, base_dir: Path | None = None) -> str:
    """A supplied file (<media> / <supplementary-material>): its caption title
    linked to the file, then its type and — when the file is in the bundle — its
    size, as Bookshelf lists supplementary data ("Read Me (MS Word, 14K)")."""
    href = el.get(f"{{{XLINK}}}href") or el.get("href") or ""
    label = el.find("label")
    title = (_caption_html(el) or (_inline(label) if label is not None else "")
             or _esc(href))
    ext = (el.get("mime-subtype") or (href.rsplit(".", 1)[-1] if "." in href else "")).lower()
    facts = [_FILE_KINDS.get(ext, ext.upper())] if ext else []
    path = base_dir / href if (base_dir is not None and href) else None
    if path is not None and path.is_file():
        facts.append(_file_size(path.stat().st_size))
    kind_html = f'<span class="small"> ({_esc(", ".join(facts))})</span>' if facts else ""
    link = f'<a href="{_esc(href)}">{title}</a>' if href else title
    return f'<p class="bk-media"{_id_attr(el.get("id"))}>{link}{kind_html}</p>'


def _render_formula(el, number: int = 0) -> str:
    """<disp-formula>: its MathML passed through as HTML <math> (browsers render
    MathML Core), with its label — Bookshelf numbers an unlabeled formula
    "(n)" by its place on the page."""
    math = el.find(f"{{{MATHML}}}math")
    body = ""
    if math is not None:
        math = etree.fromstring(etree.tostring(math))
        for node in math.iter():
            if isinstance(node.tag, str):
                node.tag = etree.QName(node).localname
        etree.cleanup_namespaces(math)
        body = etree.tostring(math, encoding="unicode", method="xml")
    label = _ws_text(el.find("label")) or (f"({number})" if number else "")
    lab = (f'<div class="bk_equ_label"><span class="nowrap">{_esc(label)}</span></div>'
           if label else "")
    return (f'<div class="bk-formula" id="{_esc(el.get("id", ""))}">'
            f'<div class="bk-formula-math">\n{body}\n</div>{lab}</div>')


def _render_ref_list(rl) -> str:
    """<ref-list>: Bookshelf's labeled list — ``dt`` the ref's <label> ("1."),
    ``dd`` the citation; a labelless list (ours, before ADR-0028) numbers by
    position.  The citation's DOI stays as text; its identifiers become the
    bracketed links after it ([PubMed: n] [CrossRef]).  The [PMC free article]
    link NCBI adds by its own lookup is not in the book and not shown."""
    items: list[str] = []
    for n, ref in enumerate(rl.findall("ref"), 1):
        label = _ws_text(ref.find("label")) or str(n)
        dt = label if label.endswith(".") else f"{label}."
        cit = ref.find("mixed-citation")
        if cit is None:
            cit = ref.find("element-citation")
        text = _citation_html(cit) if cit is not None else _esc(_ws_text(ref))
        items.append(f'<dt>{_esc(dt)}</dt><dd><div class="bk_ref"{_id_attr(ref.get("id"))}>'
                     f'{text}</div></dd>')
    rest = "".join(f"<p>{_inline(p)}</p>" for p in rl.findall("p"))
    return (f'<dl class="temp-labeled-list">{"".join(items)}</dl>' if items else "") + rest


def _citation_html(cit) -> str:
    parts = [_esc(cit.text)] if cit.text else []
    ids: dict[str, str] = {}
    for child in cit:
        if _ln(child) == "pub-id":
            kind, val = child.get("pub-id-type", ""), _ws_text(child)
            ids.setdefault(kind, val)
            if kind == "doi":
                parts.append(_esc(val))
        else:
            parts.append(_inline_child(child))
        if child.tail:
            parts.append(_esc(child.tail))
    links = []
    if ids.get("pmid"):
        links.append(f'[<a href="https://pubmed.ncbi.nlm.nih.gov/{_esc(ids["pmid"])}">PubMed'
                     f'<span class="bk_prnt">: {_esc(ids["pmid"])}</span></a>]')
    if ids.get("doi"):
        links.append(f'[<a href="https://doi.org/{_esc(ids["doi"])}">CrossRef</a>]')
    return "".join(parts).rstrip() + (" " + " ".join(links) if links else "")


def _render_sec(sec_el, level: int, out: list[str], base_dir: Path | None,
                images: dict | None) -> None:
    hl = min(level, 6)
    sid = sec_el.get("id", "")
    title = sec_el.find("title")
    label = _ws_text(sec_el.find("label"))
    anchor = f' id="{_esc(sid)}"' if sid else ""
    if title is not None or label:
        # "C.1. Gene Expression…" — Bookshelf closes a section label with a stop.
        stop = "" if label.endswith(".") else "."
        lab = f'<span class="label">{_esc(label)}{stop}</span> ' if label else ""
        text = _inline(title) if title is not None else ""
        out.append(f'<h{hl}{anchor}>{lab}{text}</h{hl}>')
    elif anchor:
        out.append(f'<span{anchor}></span>')
