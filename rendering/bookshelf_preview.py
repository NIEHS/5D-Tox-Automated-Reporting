def _page_article(page: _Page, banner: str = "", cite: str = "") -> str:
    label = f'<span class="label">{_esc(page.label)}</span>' if page.label else ""
    h1 = (f'<div class="meta-content fm-sec"><h1 id="{_esc(page.slug)}">'
          f'{label}<span class="title">{_esc(page.title)}</span></h1></div>')
    inthis = ""
    subs = [(sid, stitle) for sid, stitle in page.subnav if sid and stitle]
    if len(subs) >= 2:
        lis = "".join(f'<li><a href="#{_esc(sid)}">{_esc(stitle)}</a></li>'
                      for sid, stitle in subs)
        inthis = ('<div class="bk-inthispage"><div class="bk-inthispage-h">'
                  f'In this Page</div><ul>{lis}</ul></div>')
    return (f'<article class="bk-page" data-slug="{_esc(page.slug)}" hidden>'
            f'{banner}{h1}{inthis}<div class="body-content whole_rhythm" itemprop="text">'
            f'{page.body}</div>{cite}</article>')


def _secnav(chain: list[dict]) -> str:
    lis = []
    for p in chain:
        lab = f'<span class="n-label">{_esc(p["label"])}</span> ' if p["label"] else ""
        lis.append(f'<li data-slug="{_esc(p["slug"])}"><a href="#{_esc(p["slug"])}">'
                   f'{lab}{_esc(p["title"])}</a></li>')
    return '<ul class="bk-secnav">' + "".join(lis) + "</ul>"


def _views_panel(downloads: list[dict] | None, cite: str) -> str:
    items = ['<li><a id="bk-print" href="#">Print this page</a></li>', cite]
